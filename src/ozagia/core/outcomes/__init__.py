"""Durable outcome journal and lifecycle (Stage 1, S1-A).

Public surface::

    from ozagia.core.outcomes import OutcomeStore, follow, inspect_intent

    store = OutcomeStore(root)
    submitted = store.submit_intent("Add a module docstring", criteria=[...])
    work = store.add_work(submitted["intent_id"], "Change app/base.py")
    attempt = store.start_attempt(submitted["intent_id"], work["work_id"])
    store.finish_attempt(submitted["intent_id"], attempt["attempt_id"],
                         "succeeded")
    page = store.follow(0, intent_id=submitted["intent_id"], limit=100)
    snapshot = store.inspect(submitted["intent_id"])

The journal is canonical JSON lines under ``<state>/outcomes/``.  It is not
the code graph, the presentation session graph or the goal/run evidence
journal.  S1-B adds effects, validation evidence and gate evaluation through
the reserved record methods; S1-C adds the versioned view.
"""

